/**
 * `POST /api/media` — the browser transport for media registration and placement.
 *
 * **What it serves.** One path carries the three media writes of the "Attach media" job, selected by
 * `payload.operation`: `registerMediaAsset` (prepare uploaded bytes as a scoped asset and record its
 * renditions), `replacePlacement` (change what one placement of one draft shows, or restate its
 * description) and `removePlacement` (drop that reference from the draft). The three are separate
 * decisions with separate risks — preparing new bytes, re-describing a placed asset, and removing a
 * reference — so each keeps its own body schema and its own mutation rather than sharing a field bag.
 *
 * **The discriminant.** `payload.operation` names the mutation, which is routing metadata and not a
 * field of any payload: the service's own payload schemas are closed and declare no `operation`, so the
 * key is read first to choose one schema and removed before that mutation's strict schema reads the
 * payload. A body naming no mutation among the three is `invalid` keyed on `payload.operation`; a body
 * naming one whose own envelope or payload fails reports the messages for the offending field paths,
 * generated by the same Zod schemas the service validates with.
 *
 * **Who authorises.** Nobody here. The payload's field names, its bounds and its admission rules are the
 * mutation's, and the mutations re-derive the caller's authority from the session and re-check the
 * claimed scope, the expected revision and the produced context inside one store transaction. This file
 * states no scope, validates no payload field, reads no clock, mints no `operationId`, and never bumps,
 * rewrites or drops the caller's `expectedRevision`, so a replay still answers with the stored result and
 * a stale revision still reaches the service as a `conflict`.
 *
 * **The one thing it does carry.** The three mutations take the session they act for, and the service
 * compares it with the session its own resolver derives from the same development-session cookie — a
 * mismatch, an absent cookie and a session the store does not hold all answer `denied` inside the
 * service. So the request's own cookie value is forwarded as it stands: no identity is taken from the
 * body, none is invented when the cookie is absent, and no authority is decided here.
 *
 * **What it never does.** It opens no asset, prepares no bytes, serves no rendition and echoes nothing
 * about a file — not its name, its size, its media type or where its bytes are kept. Paste is not a
 * write path either: registering an asset records prepared renditions, and removal withdraws a reference
 * rather than the asset or any release that already served it.
 *
 * **Layering.** `app/api → modules/data-service`. This file imports the service package root and
 * `@/lib/result`, and nothing deeper: never the synthetic store, never the media module, never a
 * component or a feature. Every answer leaves through `toResponse`, the application's only status ladder.
 */

import type { NextRequest } from "next/server";
import { z } from "zod";

import { assertNever } from "@/lib/result";
import {
  mutationInputSchema,
  mutations,
  outcomeFromError,
  toResponse,
  type MutationInput,
  type MutationOutcome,
} from "@/modules/data-service";
import { sessionIdOf } from "../session-cookie";

// The store writes through node:fs and media preparation loads Node-API native bindings, so this
// handler never runs on the edge runtime.
export const runtime = "nodejs";
// Every request resolves the development session and evaluates the scenario clock afresh.
export const dynamic = "force-dynamic";

/**
 * The marker the service puts on an attempt that carries no identity of its own.
 *
 * An `invalid` answer still names an attempt, and a body so malformed that it states no `operationId`
 * has no other identity to report. Matching the service's own marker keeps the two answers alike.
 */
const UNIDENTIFIED_ATTEMPT = "unidentified-attempt";

/**
 * The two messages this file words itself.
 *
 * Everything else a refusal says about a field comes from the Zod schema that declared it, so a worker
 * who corrects a field is never told one thing by the transport and another by the service.
 */
const MESSAGES = {
  operationRequired:
    "State which change this request makes as payload.operation: registerMediaAsset, replacePlacement or removePlacement.",
  bodyNotJson:
    "Send the change as a JSON object carrying operationId, scope, expectedRevision and payload.",
} as const;
// ---------------------------------------------------------------------------------------------
// One body schema per mutation: the four-field envelope, with that mutation's own payload type
//
// Each payload type is taken from the mutation that validates it, so a field the service adds, renames
// or bounds differently is a compile error here instead of a second declaration that drifts. No payload
// field is restated, because the mutation's own closed schema already answers for every one of them.
// ---------------------------------------------------------------------------------------------

/** The payload `registerMediaAsset` accepts. */
type RegisterMediaAssetPayload = Parameters<
  typeof mutations.media.registerMediaAsset
>[1]["payload"];

/** The payload `replacePlacement` and `removePlacement` accept. */
type PlacementTargetPayload = Parameters<typeof mutations.media.replacePlacement>[1]["payload"];

/** The registration body's payload: the mutation's own payload, plus the routing discriminant. */
type RegisterMediaAssetRequest = RegisterMediaAssetPayload & {
  readonly operation: "registerMediaAsset";
};

/** A replacement body's payload: the mutation's own payload, plus the routing discriminant. */
type ReplacePlacementRequest = PlacementTargetPayload & { readonly operation: "replacePlacement" };

/** A removal body's payload: the mutation's own payload, plus the routing discriminant. */
type RemovePlacementRequest = PlacementTargetPayload & { readonly operation: "removePlacement" };

/**
 * The closed set of mutations this path dispatches, in the order the plan states them.
 *
 * A fourth name is not a routing decision to add here: a bulk verb, a draft write or a reach change
 * belongs to the path that serves it, and naming it on this path answers `invalid` rather than reaching
 * a mutation this transport never validated a schema for.
 */
const MEDIA_OPERATIONS = ["registerMediaAsset", "replacePlacement", "removePlacement"] as const;

/** The registration request: the four-field envelope around this mutation's payload. */
const registerMediaAssetBodySchema = mutationInputSchema(z.custom<RegisterMediaAssetRequest>());

/** The replacement request: the same envelope around the placement target payload. */
const replacePlacementBodySchema = mutationInputSchema(z.custom<ReplacePlacementRequest>());

/** The removal request: the same envelope around the same placement target payload. */
const removePlacementBodySchema = mutationInputSchema(z.custom<RemovePlacementRequest>());

// ---------------------------------------------------------------------------------------------
// Reading the request
// ---------------------------------------------------------------------------------------------

/** The attempt identity a body states, so a refusal can name the attempt the caller can replay. */
const attemptIdentitySchema = z.object({ operationId: z.string() });

/**
 * The discriminant as the transport requires it: `payload.operation`, one of the three mutation names.
 *
 * Only the discriminant is read here, so a body carrying extra keys is not refused at this point: the
 * chosen mutation's own closed schema reports those against their own field paths.
 */
const discriminantSchema = z.object(
  {
    payload: z.object(
      { operation: z.enum(MEDIA_OPERATIONS, { error: MESSAGES.operationRequired }) },
      { error: MESSAGES.operationRequired },
    ),
  },
  { error: MESSAGES.bodyNotJson },
);

/** The request body, or `undefined` when it is absent or is not valid JSON. */
async function jsonBodyOf(request: Request): Promise<unknown> {
  try {
    const body: unknown = await request.json();
    return body;
  } catch {
    return undefined;
  }
}

/** The attempt identity to report on a refusal, read defensively: a malformed body states none. */
function operationIdentityOf(raw: unknown): string {
  const identity = attemptIdentitySchema.safeParse(raw);
  return identity.success && identity.data.operationId.length > 0
    ? identity.data.operationId
    : UNIDENTIFIED_ATTEMPT;
}

/**
 * The payload a mutation receives: the routing discriminant removed, everything else as stated.
 *
 * The mutation's own schema is closed and declares no `operation` field, so leaving the discriminant in
 * place would turn every registration and placement change into an unrecognised-key refusal. Removing it
 * here is what keeps the field a routing fact rather than a second description of the media.
 */
function payloadOf<T extends { readonly operation: string }>(payload: T): Omit<T, "operation"> {
  const { operation: _discriminant, ...forwarded } = payload;
  return forwarded;
}

/**
 * Validates one body against one mutation's own request schema, then calls exactly that mutation once.
 *
 * The four contract fields are forwarded untouched, `expectedRevision` and `operationId` included, so a
 * replay still answers with the stored result instead of applying a second effect and a stale revision
 * still reaches the service as a `conflict`. Nothing is minted, bumped or stripped but the discriminant.
 */
async function dispatch<P extends { readonly operation: string }>(
  schema: z.ZodType<MutationInput<P>>,
  raw: unknown,
  operationId: string,
  run: (input: MutationInput<Omit<P, "operation">>) => Promise<MutationOutcome>,
): Promise<Response> {
  const parsed = schema.safeParse(raw);
  if (!parsed.success) {
    return toResponse(outcomeFromError(operationId, parsed.error));
  }
  return toResponse(await run({ ...parsed.data, payload: payloadOf(parsed.data.payload) }));
}

// ---------------------------------------------------------------------------------------------
// The one verb
// ---------------------------------------------------------------------------------------------

/**
 * One named media mutation, selected by `payload.operation`.
 *
 * Every answer is one of the eight outcomes with its own status, so a client never infers success from
 * an absent error: a stale revision is a `conflict` that preserves the submitted input, a replay is
 * `alreadyAccepted` with the stored result, bytes the media pipeline refused are `invalid` with the
 * pipeline's own reason and next step, and a discriminant naming no mutation among the three is
 * `invalid` naming `payload.operation`.
 *
 * A thrown fault is answered rather than escaping the boundary: `outcomeFromError` knows the difference
 * between a store outage, a session that cannot be established and a lost acknowledgement, and no fault
 * is answered with seeded data or with an asset this file invented.
 */
export async function POST(request: NextRequest): Promise<Response> {
  const raw = await jsonBodyOf(request);
  const operationId = operationIdentityOf(raw);
  const claimed = discriminantSchema.safeParse(raw);

  if (!claimed.success) {
    return toResponse(outcomeFromError(operationId, claimed.error));
  }

  try {
    const sessionId = sessionIdOf(request);

    switch (claimed.data.payload.operation) {
      case "registerMediaAsset":
        return await dispatch(registerMediaAssetBodySchema, raw, operationId, (input) =>
          mutations.media.registerMediaAsset(sessionId, input),
        );
      case "replacePlacement":
        return await dispatch(replacePlacementBodySchema, raw, operationId, (input) =>
          mutations.media.replacePlacement(sessionId, input),
        );
      case "removePlacement":
        return await dispatch(removePlacementBodySchema, raw, operationId, (input) =>
          mutations.media.removePlacement(sessionId, input),
        );
      default:
        // Unreachable: the three names above are the closed set the discriminant schema admits, so a
        // fourth mutation fails to compile at this call instead of reaching the runtime.
        return assertNever(claimed.data.payload.operation, "Unhandled media mutation");
    }
  } catch (error) {
    // An exception here is a defect rather than a presentation: the service answers refusals as
    // outcomes, so a throw means a store or medium fault, or a failure whose fate is not known.
    return toResponse(outcomeFromError(operationId, error));
  }
}
